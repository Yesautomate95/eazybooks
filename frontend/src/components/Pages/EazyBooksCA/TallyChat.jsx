// Table component for displaying SQL results
const DataTable = ({ data }) => {
  const [tableData, setTableData] = useState([]);

  // Parse the JSON string if it's a string
  const tableDataMemo = useMemo(() => {
    if (!data) return [];
    if (typeof data === 'string') {
      try {
        return JSON.parse(data);
      } catch (e) {
        return [];
      }
    }
    return Array.isArray(data) ? data : [data];
  }, [data]);

  // Function to format the data as clean, readable text for sharing
  const getFormattedTextForSharing = () => {
    if (!tableDataMemo || tableDataMemo.length === 0) return '';
    
    // Get headers
    const headers = Object.keys(tableDataMemo[0]);
    
    // Format headers with proper capitalization
    const formattedHeaders = headers.map(header => 
      header.charAt(0).toUpperCase() + header.slice(1).replace(/_/g, ' ')
    ).join(' | ');

    // Format rows
    const rows = tableDataMemo.map(row => 
      headers.map(header => {
        const value = row[header] ?? '';
        return String(value);
      }).join(' | ')
    );

    // Create a nicely formatted text output
    return `*Tally Data Report*\n\n${formattedHeaders}\n${'—'.repeat(formattedHeaders.length/2)}\n${rows.join('\n')}\n\n_Generated by EazyBooks_`;
  };

  // Share via WhatsApp - open in the same tab
  const handleWhatsAppShare = (e) => {
    e.preventDefault();
    const formattedText = getFormattedTextForSharing();
    const encodedText = encodeURIComponent(formattedText);
    
    // Open WhatsApp in the same tab
    window.location.href = `https://wa.me/?text=${encodedText}`;
  };

  // Share via Email
  const handleEmailShare = () => {
    const formattedText = getFormattedTextForSharing();
    const subject = "Tally Data Report";
    window.location.href = `mailto:?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(formattedText)}`;
  };

  // Copy to clipboard
  const handleCopyToClipboard = () => {
    const formattedText = getFormattedTextForSharing();
    navigator.clipboard.writeText(formattedText)
      .then(() => {
        alert('Data copied to clipboard!');
      })
      .catch(err => {
        console.error('Failed to copy: ', err);
        alert('Failed to copy data to clipboard');
      });
  };

  // Export to Excel
  const handleExportToExcel = () => {
    if (!tableDataMemo || tableDataMemo.length === 0) {
      alert('No data to export');
      return;
    }

    try {
      // Create a new workbook
      const workbook = XLSX.utils.book_new();
      
      // Convert JSON data to worksheet
      const worksheet = XLSX.utils.json_to_sheet(tableDataMemo);
      
      // Add the worksheet to the workbook
      XLSX.utils.book_append_sheet(workbook, worksheet, 'Tally Data');
      
      // Generate Excel file buffer
      const excelBuffer = XLSX.write(workbook, { bookType: 'xlsx', type: 'array' });
      
      // Create Blob and save the file
      const blob = new Blob([excelBuffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
      saveAs(blob, `TallyData_${new Date().toISOString().slice(0,10)}.xlsx`);
    } catch (error) {
      console.error('Error exporting to Excel:', error);
      alert('Failed to export data to Excel');
    }
  };

  // Generate columns from the first row of data
  const columns = useMemo(() => {
    if (!tableDataMemo || tableDataMemo.length === 0) return [];
    const firstRow = tableDataMemo[0];
    if (!firstRow) return [];
    return Object.keys(firstRow).map(key => ({
      accessorKey: key,
      header: key.charAt(0).toUpperCase() + key.slice(1).replace(/_/g, ' '),
      cell: info => {
        const value = info.getValue();
        // Handle different data types
        if (value === null || value === undefined) return '-';
        if (typeof value === 'boolean') return value ? 'Yes' : 'No';
        if (typeof value === 'object') return JSON.stringify(value);
        return String(value);
      },
    }));
  }, [tableDataMemo]);

  const table = useReactTable({
    data: tableDataMemo,
    columns,
    getCoreRowModel: getCoreRowModel(),
    getSortedRowModel: getSortedRowModel(),
    getPaginationRowModel: getPaginationRowModel(),
  });

  if (!data) {
    return (
      <div className="text-center py-8 text-gilt-faint">
        Unable to fetch data. Please try again later.
      </div>
    );
  }

  if (tableDataMemo.length === 0) {
    return (
      <div className="text-center py-8 text-gilt-faint">
        No data available.
      </div>
    );
  }

  return (
    <div className="mt-4">
      <div className="overflow-x-auto rounded-lg border border-gilt-hairline bg-gilt-card">
        <table className="min-w-full divide-y divide-gilt-hairline">
          <thead className="bg-gilt-sunken">
            {table.getHeaderGroups().map(headerGroup => (
              <tr key={headerGroup.id}>
                {headerGroup.headers.map(header => (
                  <th
                    key={header.id}
                    className="px-6 py-3 text-left text-xs font-medium text-gilt-soft uppercase tracking-wider cursor-pointer hover:text-gilt-ink transition-colors duration-150"
                    onClick={header.column.getToggleSortingHandler()}
                  >
                    <div className="flex items-center space-x-1">
                      <span>{flexRender(header.column.columnDef.header, header.getContext())}</span>
                      <span className="text-gilt-brass">
                        {{
                          asc: '↑',
                          desc: '↓',
                        }[header.column.getIsSorted()] ?? ''}
                      </span>
                    </div>
                  </th>
                ))}
              </tr>
            ))}
          </thead>
          <tbody className="bg-gilt-card divide-y divide-gilt-hairline">
            {table.getRowModel().rows.map(row => (
              <tr key={row.id} className="hover:bg-gilt-sunken transition-colors duration-150">
                {row.getVisibleCells().map(cell => (
                  <td key={cell.id} className="px-6 py-4 whitespace-nowrap font-mono text-[13px] tabular-nums text-gilt-soft">
                    {flexRender(cell.column.columnDef.cell, cell.getContext())}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
        <div className="px-6 py-3 flex flex-col gap-3 border-t border-gilt-hairline bg-gilt-sunken">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2">
              <button
                className="px-3 py-1 border border-gilt-hairline rounded-md text-sm text-gilt-soft bg-gilt-card hover:text-gilt-ink hover:border-gilt-brass transition-colors duration-150 disabled:opacity-50 disabled:hover:border-gilt-hairline"
                onClick={() => table.previousPage()}
                disabled={!table.getCanPreviousPage()}
              >
                Previous
              </button>
              <button
                className="px-3 py-1 border border-gilt-hairline rounded-md text-sm text-gilt-soft bg-gilt-card hover:text-gilt-ink hover:border-gilt-brass transition-colors duration-150 disabled:opacity-50 disabled:hover:border-gilt-hairline"
                onClick={() => table.nextPage()}
                disabled={!table.getCanNextPage()}
              >
                Next
              </button>
              <span className="font-mono text-xs tabular-nums text-gilt-soft">
                Page {table.getState().pagination.pageIndex + 1} of{' '}
                {table.getPageCount()}
              </span>
            </div>
            <select
              className="px-2 py-1 border border-gilt-hairline rounded-md font-mono text-xs tabular-nums text-gilt-soft bg-gilt-card hover:text-gilt-ink transition-colors duration-150"
              value={table.getState().pagination.pageSize}
              onChange={e => table.setPageSize(Number(e.target.value))}
            >
              {[10, 25, 50].map(pageSize => (
                <option key={pageSize} value={pageSize}>
                  Show {pageSize}
                </option>
              ))}
            </select>
          </div>
          
          <div className="flex items-center gap-2 flex-wrap">
            <button
              onClick={handleWhatsAppShare}
              className="flex items-center gap-2 px-3 py-2 rounded-md text-sm border border-gilt-hairline bg-gilt-card text-gilt-soft hover:text-gilt-ink hover:border-gilt-brass transition-colors duration-150"
              title="Share directly to WhatsApp"
            >
              <Share2 size={16} />
              <span>WhatsApp</span>
            </button>

            <button
              onClick={handleEmailShare}
              className="flex items-center gap-2 px-3 py-2 rounded-md text-sm border border-gilt-hairline bg-gilt-card text-gilt-soft hover:text-gilt-ink hover:border-gilt-brass transition-colors duration-150"
              title="Share via Email"
            >
              <Mail size={16} />
              <span>Email</span>
            </button>

            <button
              onClick={handleCopyToClipboard}
              className="flex items-center gap-2 px-3 py-2 rounded-md text-sm border border-gilt-hairline bg-gilt-card text-gilt-soft hover:text-gilt-ink hover:border-gilt-brass transition-colors duration-150"
              title="Copy to clipboard"
            >
              <Copy size={16} />
              <span>Copy</span>
            </button>

            <button
              onClick={handleExportToExcel}
              className="flex items-center gap-2 px-3 py-2 rounded-md text-sm border border-gilt-hairline bg-gilt-card text-gilt-soft hover:text-gilt-ink hover:border-gilt-brass transition-colors duration-150"
              title="Download as Excel file"
            >
              <Download size={16} />
              <span>Excel</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};

const SqlPanel = ({ sql, purpose, rejected, error, rowCount, truncated, children }) => {
  const [open, setOpen] = useState(false);
  const summary = rejected
    ? `SQL rejected — ${rejected}`
    : error
      ? `SQL error — ${error}`
      : rowCount === null || rowCount === undefined
        ? (purpose || "Running SQL...")
        : `${rowCount} row${rowCount === 1 ? "" : "s"}${truncated ? " (truncated)" : ""}${purpose ? ` — ${purpose}` : ""}`;
  const tone = rejected || error
    ? "bg-gilt-card border-gilt-debit/40 text-gilt-debit"
    : "bg-gilt-card border-gilt-hairline text-gilt-soft";

  return (
    <div className={`border rounded-lg ${tone}`}>
      <button
        type="button"
        onClick={() => setOpen(o => !o)}
        className="w-full flex items-center justify-between px-3 py-2 font-mono text-xs tabular-nums font-medium hover:opacity-80 transition-opacity duration-150"
      >
        <span className="flex items-center gap-2 text-left">
          <Terminal size={14} className="text-gilt-brass" />
          <span className="truncate">{summary}</span>
        </span>
        {open ? <ChevronUp size={14} /> : <ChevronDown size={14} />}
      </button>
      {open && (
        <div className="px-3 pb-3 pt-1 space-y-2">
          <pre className="text-xs whitespace-pre-wrap font-mono overflow-x-auto">{sql}</pre>
          {children}
        </div>
      )}
    </div>
  );
};

